/* Dashboard uploads use one self-contained TypeScript file per Edge Function. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, 'supabase/functions', file), 'utf8');
const internal = source => source.replace(/^import .* from ["']\.\.?\/.*["'];\r?\n/gm, '').replace(/^export /gm, '');
const modules = {
  'native-device': ['app-origins', 'fcm', 'native-device'],
  'send-push': ['fcm', 'web-push-delivery'],
  'admin-set-password': ['app-origins', 'admin-set-password'],
};
for (const [name, dependencies] of Object.entries(modules)) {
  const source = internal(read(name + '/index.ts'));
  const imports = source.match(/^import .*;\r?$/gm) || [];
  const body = source.replace(/^import .*;\r?\n/gm, '');
  const output = path.join(root, 'artifacts/supabase', name + '.ts');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const helpers = dependencies.map(file => internal(read('_shared/' + file + '.ts')));
  fs.writeFileSync(output, '// Generated by scripts/prepare-deployment.cjs; secrets are read only from Supabase environment.\n' +
    [imports.join('\n'), ...helpers, body].join('\n'));
}
console.log('Prepared three self-contained Edge Function uploads; no credentials included.');
